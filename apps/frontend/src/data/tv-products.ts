function tvSpecs(
  display: string,
  resolution: string,
  hdr: string,
  smart: string,
): ProductSeed['specifications'] {
  return [
    { group: 'Display', key: 'Size', value: display, position: 1 },
    { group: 'Display', key: 'Resolution', value: resolution, position: 2 },
    { group: 'HDR', key: 'Formats', value: hdr, position: 1 },
    { group: 'Smart TV', key: 'Platform', value: smart, position: 1 },
  ];
}

