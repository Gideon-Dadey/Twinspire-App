function accessorySpecs(
  connectivity: string,
  battery: string,
  compatibility: string,
  extras: string,
): ProductSeed['specifications'] {
  return [
    { group: 'Connectivity', key: 'Wireless', value: connectivity, position: 1 },
    { group: 'Battery', key: 'Runtime', value: battery, position: 1 },
    { group: 'Compatibility', key: 'Works with', value: compatibility, position: 1 },
    { group: 'Highlights', key: 'Features', value: extras, position: 1 },
  ];
}

