function cpuSpecs(
  cores: string,
  clocks: string,
  tdp: string,
  socket: string,
): ProductSeed['specifications'] {
  return [
    { group: 'CPU', key: 'Cores / Threads', value: cores, position: 1 },
    { group: 'CPU', key: 'Base / Boost', value: clocks, position: 2 },
    { group: 'CPU', key: 'TDP', value: tdp, position: 3 },
    { group: 'Platform', key: 'Socket', value: socket, position: 1 },
  ];
}

function gpuSpecs(
  cores: string,
  memory: string,
  boost: string,
  tgp: string,
): ProductSeed['specifications'] {
  return [
    { group: 'GPU', key: 'Compute units', value: cores, position: 1 },
    { group: 'GPU', key: 'Memory', value: memory, position: 2 },
    { group: 'GPU', key: 'Boost clock', value: boost, position: 3 },
    { group: 'GPU', key: 'Board power', value: tgp, position: 4 },
  ];
}

function ramSpecs(
  capacity: string,
  speed: string,
  timings: string,
  voltage: string,
): ProductSeed['specifications'] {
  return [
    { group: 'Memory', key: 'Capacity', value: capacity, position: 1 },
    { group: 'Memory', key: 'Speed', value: speed, position: 2 },
    { group: 'Memory', key: 'Timings', value: timings, position: 3 },
    { group: 'Memory', key: 'Voltage', value: voltage, position: 4 },
  ];
}

function ssdSpecs(
  capacity: string,
  seqRead: string,
  seqWrite: string,
  form: string,
): ProductSeed['specifications'] {
  return [
    { group: 'Storage', key: 'Capacity', value: capacity, position: 1 },
    { group: 'Storage', key: 'Seq. read', value: seqRead, position: 2 },
    { group: 'Storage', key: 'Seq. write', value: seqWrite, position: 3 },
    { group: 'Storage', key: 'Form factor', value: form, position: 4 },
  ];
}

